def _set_font(run, size, color=TEXT, bold=False, italic=False):
    f = run.font
    f.name = FONT
    f.size = Pt(size)
    f.bold = bold
    f.italic = italic
    f.color.rgb = color


def _parse(text):
    """'**bold** normal' -> [(seg, bold)]"""
    parts = text.split("**")
    return [(p, i % 2 == 1) for i, p in enumerate(parts) if p]


def add_runs(par, text, size, color, bold=False, link=None, italic=False):
    for seg, b in _parse(text):
        r = par.add_run()
        r.text = seg
        _set_font(r, size, color, bold or b, italic)
        if link:
            r.hyperlink.address = link
            _set_font(r, size, color, bold or b, italic)


def tb(slide, x, y, w, h, paras, size=14, color=TEXT, align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP,
       margin=0.05, space_after=4, line_spacing=None, name=None):
    """paras: list of str | dict(text, size, color, bold, bullet, link, align, italic, space_after)"""
    box = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    if name:
        box.name = name
    tf = box.text_frame
    tf.word_wrap = True
    tf.auto_size = None
    for side in ("left", "right", "top", "bottom"):
        setattr(tf, f"margin_{side}", Inches(margin))
    tf.vertical_anchor = anchor
    if isinstance(paras, (str, dict)):
        paras = [paras]
    for i, p in enumerate(paras):
        if isinstance(p, str):
            p = {"text": p}
        par = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        par.alignment = p.get("align", align)
        par.space_after = Pt(p.get("space_after", space_after))
        if line_spacing:
            par.line_spacing = line_spacing
        if p.get("bullet"):
            _bullet(par, p.get("bullet_char", "•"), p.get("size", size), p.get("bullet_color", GREEN))
        add_runs(par, p["text"], p.get("size", size), p.get("color", color), p.get("bold", False),
                 p.get("link"), p.get("italic", False))
    return box


def _bullet(par, char, size, color):
    pPr = par._p.get_or_add_pPr()
    indent = int(Inches(0.2 + size / 300))
    pPr.set("marL", str(indent))
    pPr.set("indent", str(-indent))
    for tag in ("a:buClr", "a:buSzPct", "a:buFont", "a:buChar", "a:buNone"):
        for el in pPr.findall(qn(tag)):
            pPr.remove(el)
    buClr = etree.SubElement(pPr, qn("a:buClr"))
    clr = etree.SubElement(buClr, qn("a:srgbClr"))
    clr.set("val", str(color))
    buFont = etree.SubElement(pPr, qn("a:buFont"))
    buFont.set("typeface", "Arial")
    buChar = etree.SubElement(pPr, qn("a:buChar"))
    buChar.set("char", char)


def rect(slide, x, y, w, h, fill=GREY_LT, line=None, shape=MSO_SHAPE.RECTANGLE, radius=None, name=None,
         line_w=1.0, dash=False, shadow=False):
    s = slide.shapes.add_shape(shape, Inches(x), Inches(y), Inches(w), Inches(h))
    if name:
        s.name = name
    if fill is None:
        s.fill.background()
    else:
        s.fill.solid()
        s.fill.fore_color.rgb = fill
    if line is None:
        s.line.fill.background()
    else:
        s.line.color.rgb = line
        s.line.width = Pt(line_w)
        if dash:
            s.line.dash_style = 4  # MSO_LINE.DASH
    if radius is not None and shape == MSO_SHAPE.ROUNDED_RECTANGLE:
        s.adjustments[0] = radius
    if not shadow:
        # explicitly remove theme shadow / effects
        spPr = s._element.spPr
        if spPr.find(qn("a:effectLst")) is None:
            etree.SubElement(spPr, qn("a:effectLst"))
        st = s._element.find(qn("p:style"))
        if st is not None:
            er = st.find(qn("a:effectRef"))
            if er is not None:
                er.set("idx", "0")
    s.text_frame.text = ""
    return s


