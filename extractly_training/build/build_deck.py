def table(slide, x, y, w, data, col_w, size=12, header_fill=NAVY, row_h=0.32, zebra=True, bold_first_col=False,
          name="Table", align=None):
    rows, cols = len(data), len(data[0])
    gs = slide.shapes.add_table(rows, cols, Inches(x), Inches(y), Inches(w), Inches(row_h * rows))
    gs.name = name
    t = gs.table
    # remove default table style banding look
    tblPr = t._tbl.tblPr
    tblPr.set("firstRow", "1"); tblPr.set("bandRow", "0")
    for j, cw in enumerate(col_w):
        t.columns[j].width = Inches(cw)
    for i in range(rows):
        t.rows[i].height = Inches(row_h)
        for j in range(cols):
            cell = t.cell(i, j)
            cell.margin_left = cell.margin_right = Inches(0.06)
            cell.margin_top = cell.margin_bottom = Inches(0.03)
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            tf = cell.text_frame
            tf.word_wrap = True
            tf.text = ""
            val = data[i][j]
            p = tf.paragraphs[0]
            if align and align[j]:
                p.alignment = align[j]
            if i == 0:
                add_runs(p, str(val), size, WHITE, True)
                cell.fill.solid(); cell.fill.fore_color.rgb = header_fill
            else:
                add_runs(p, str(val), size, TEXT, bold_first_col and j == 0)
                cell.fill.solid()
                cell.fill.fore_color.rgb = GREY_LT if (zebra and i % 2 == 0) else WHITE
    return gs


