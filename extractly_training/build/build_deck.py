def render_page(pdf, dpi=200):
    base = os.path.join(IMG, os.path.basename(pdf)[:-4] + f"_{dpi}")
    if not os.path.exists(base + ".png"):
        subprocess.run(["pdftoppm", "-r", str(dpi), "-png", "-singlefile", pdf, base], check=True)
    return base + ".png", dpi


def doc_image(slide, pdf, crop, x, y, w, name, border=True):
    """Insert a crop (inches on the letter page: x0,y0,x1,y1) of a fictional PDF.
    Returns a mapper (doc_x, doc_y) -> slide inches and the scale factor."""
    png, dpi = render_page(pdf)
    x0, y0, x1, y1 = crop
    im = Image.open(png)
    c = im.crop((int(x0 * dpi), int(y0 * dpi), int(x1 * dpi), int(y1 * dpi)))
    out = os.path.join(IMG, f"{name}.png")
    c.save(out)
    scale = w / (x1 - x0)
    h = (y1 - y0) * scale
    pic = slide.shapes.add_picture(out, Inches(x), Inches(y), Inches(w), Inches(h))
    pic.name = name
    if border:
        pic.line.color.rgb = GREY_MID
        pic.line.width = Pt(0.75)
    mapper = lambda dx, dy: (x + (dx - x0) * scale, y + (dy - y0) * scale)
    return mapper, scale, h


